import Foundation

/// Builds plain-text and interactive HTML download manifests for missing series works.
enum SeriesGapManifestBuilder {

    /// Generates a plain-text manifest file compatible with `ao3downloader -f` and FanFicFare.
    static func generateTextManifest(report: SeriesGapReport) -> String {
        let dateString = ISO8601DateFormatter().string(from: Date())
        let authors = report.authors.isEmpty ? "Unknown" : report.authors.joined(separator: ", ")

        var lines: [String] = []
        lines.append("# Series: \(report.seriesName) by \(authors)")
        lines.append("# Coverage: \(report.presentIndices.count) of \(report.totalKnownParts) works present (\(report.coveragePercentageString))")
        lines.append("# Missing parts: \(report.missingIndices.map(String.init).joined(separator: ", "))")
        lines.append("# Generated by Ambrosia on \(dateString)")
        lines.append("# Run with: ao3downloader -f \(safeFilename(report.seriesName)).txt")
        lines.append("")

        let urls = report.targetDownloadURLs
        if !urls.isEmpty {
            for url in urls {
                lines.append(url.absoluteString)
            }
        } else if let seriesID = report.ao3SeriesID {
            lines.append("https://archiveofourown.org/series/\(seriesID)")
        } else {
            lines.append("# No direct URLs could be derived for this series.")
        }

        return lines.joined(separator: "\n") + "\n"
    }

    /// Generates a styled, self-contained, offline interactive HTML dashboard.
    static func generateHTMLManifest(report: SeriesGapReport) -> String {
        let authors = report.authors.isEmpty ? "Unknown Author" : report.authors.joined(separator: ", ")
        let percent = Int(report.coverageFraction * 100)
        let urls = report.targetDownloadURLs.map(\.absoluteString)
        let urlsJSON = (try? String(data: JSONEncoder().encode(urls), encoding: .utf8)) ?? "[]"

        var tableRows = ""
        for item in report.items {
            let statusBadge = item.isPresent
                ? "<span class=\"badge present\">In Library</span>"
                : "<span class=\"badge missing\">Missing</span>"

            let words = item.wordCount.map { "\($0) words" } ?? "—"
            let linkHTML: String
            if let url = item.url {
                linkHTML = "<a href=\"\(url.absoluteString)\" target=\"_blank\" class=\"btn link-btn\">View on AO3</a>"
            } else {
                linkHTML = "<span class=\"muted\">No Link</span>"
            }

            tableRows += """
            <tr class="\(item.isPresent ? "row-present" : "row-missing")">
                <td class="part-col">Part \(item.partIndex)</td>
                <td class="status-col">\(statusBadge)</td>
                <td class="title-col">\(xmlEscape(item.title))</td>
                <td class="words-col">\(words)</td>
                <td class="action-col">\(linkHTML)</td>
            </tr>\n
            """
        }

        return """
        <!DOCTYPE html>
        <html lang="en">
        <head>
            <meta charset="utf-8">
            <meta name="viewport" content="width=device-width, initial-scale=1">
            <title>Series Update: \(xmlEscape(report.seriesName))</title>
            <style>
                :root {
                    --bg: #1e1e24;
                    --card-bg: #282830;
                    --text: #e2e8f0;
                    --muted: #94a3b8;
                    --accent: #990000;
                    --accent-hover: #b30000;
                    --border: #3b3b48;
                    --green: #22c55e;
                    --green-bg: rgba(34, 197, 94, 0.15);
                    --red: #ef4444;
                    --red-bg: rgba(239, 68, 68, 0.15);
                }
                @media (prefers-color-scheme: light) {
                    :root {
                        --bg: #f8fafc;
                        --card-bg: #ffffff;
                        --text: #1e293b;
                        --muted: #64748b;
                        --border: #e2e8f0;
                    }
                }
                body {
                    font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
                    background: var(--bg);
                    color: var(--text);
                    margin: 0;
                    padding: 32px 20px;
                    line-height: 1.5;
                }
                .container {
                    max-width: 860px;
                    margin: 0 auto;
                }
                .card {
                    background: var(--card-bg);
                    border: 1px solid var(--border);
                    border-radius: 12px;
                    padding: 24px;
                    margin-bottom: 24px;
                    box-shadow: 0 4px 6px -1px rgba(0,0,0,0.1);
                }
                h1 {
                    font-size: 24px;
                    margin: 0 0 6px 0;
                }
                .subtitle {
                    color: var(--muted);
                    font-size: 14px;
                    margin-bottom: 20px;
                }
                .progress-container {
                    margin: 16px 0 20px 0;
                }
                .progress-label {
                    display: flex;
                    justify-content: space-between;
                    font-size: 13px;
                    font-weight: 600;
                    margin-bottom: 6px;
                }
                .progress-bar-bg {
                    background: var(--border);
                    height: 10px;
                    border-radius: 5px;
                    overflow: hidden;
                }
                .progress-bar-fill {
                    background: var(--accent);
                    height: 100%;
                    width: \(percent)%;
                    border-radius: 5px;
                    transition: width 0.3s ease;
                }
                .btn {
                    display: inline-block;
                    padding: 8px 16px;
                    border-radius: 6px;
                    font-size: 13px;
                    font-weight: 500;
                    cursor: pointer;
                    text-decoration: none;
                    border: none;
                    transition: all 0.15s ease;
                }
                .btn-primary {
                    background: var(--accent);
                    color: #fff;
                }
                .btn-primary:hover {
                    background: var(--accent-hover);
                }
                .link-btn {
                    background: var(--border);
                    color: var(--text);
                    padding: 4px 10px;
                    font-size: 12px;
                }
                .link-btn:hover {
                    opacity: 0.85;
                }
                table {
                    width: 100%;
                    border-collapse: collapse;
                    font-size: 13px;
                }
                th, td {
                    padding: 10px 12px;
                    text-align: left;
                    border-bottom: 1px solid var(--border);
                }
                th {
                    color: var(--muted);
                    font-weight: 600;
                }
                .badge {
                    padding: 2px 8px;
                    border-radius: 9999px;
                    font-size: 11px;
                    font-weight: 600;
                }
                .badge.present {
                    background: var(--green-bg);
                    color: var(--green);
                }
                .badge.missing {
                    background: var(--red-bg);
                    color: var(--red);
                }
                .muted {
                    color: var(--muted);
                }
                .header-actions {
                    display: flex;
                    gap: 12px;
                    margin-top: 16px;
                }
                footer {
                    text-align: center;
                    font-size: 12px;
                    color: var(--muted);
                    margin-top: 32px;
                }
            </style>
        </head>
        <body>
            <div class="container">
                <div class="card">
                    <h1>\(xmlEscape(report.seriesName))</h1>
                    <div class="subtitle">by \(xmlEscape(authors))</div>

                    <div class="progress-container">
                        <div class="progress-label">
                            <span>Library Coverage</span>
                            <span>\(report.presentIndices.count) of \(report.totalKnownParts) Works (\(percent)%)</span>
                        </div>
                        <div class="progress-bar-bg">
                            <div class="progress-bar-fill"></div>
                        </div>
                    </div>

                    <div class="header-actions">
                        <button id="copyBtn" class="btn btn-primary" onclick="copyUrls()">Copy Download URLs</button>
                    </div>
                </div>

                <div class="card" style="padding: 0; overflow: hidden;">
                    <table>
                        <thead>
                            <tr>
                                <th style="width: 80px;">Part</th>
                                <th style="width: 100px;">Status</th>
                                <th>Title</th>
                                <th style="width: 110px;">Length</th>
                                <th style="width: 120px;">Action</th>
                            </tr>
                        </thead>
                        <tbody>
                            \(tableRows)
                        </tbody>
                    </table>
                </div>

                <footer>
                    Generated by Ambrosia &bull; Compatible with ao3downloader &amp; FanFicFare
                </footer>
            </div>

            <script>
                const downloadURLs = \(urlsJSON);
                function copyUrls() {
                    const btn = document.getElementById('copyBtn');
                    if (!downloadURLs.length) {
                        btn.textContent = 'No URLs Available';
                        return;
                    }
                    navigator.clipboard.writeText(downloadURLs.join('\\n')).then(() => {
                        const original = btn.textContent;
                        btn.textContent = 'Copied ' + downloadURLs.length + ' URL' + (downloadURLs.length === 1 ? '' : 's') + '!';
                        setTimeout(() => { btn.textContent = original; }, 2000);
                    }).catch(err => {
                        alert('Could not copy to clipboard: ' + err);
                    });
                }
            </script>
        </body>
        </html>
        """
    }

    private static func safeFilename(_ name: String) -> String {
        let invalid = CharacterSet(charactersIn: "\\/:*?\"<>| &")
        return name.components(separatedBy: invalid).joined(separator: "_")
    }
}
